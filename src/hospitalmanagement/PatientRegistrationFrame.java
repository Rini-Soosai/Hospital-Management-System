    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        String name=txtPatientName.getText().trim();
        String ageText=txtAge.getText().trim();
        String phone=txtPhoneNumber.getText().trim();
        String address=txtAddress.getText().trim();
        
        String gender="";
        if(rdoMale.isSelected()){
        gender="Male";}
        else if(rdoFemale.isSelected()){
        gender="Female";}
        else if(rdoOther.isSelected()){
        gender="Other";}
        
        if(name.isEmpty() || ageText.isEmpty()){
        JOptionPane.showMessageDialog(this,"Please enter the name and age");
        return;}
        
        int age;
        try{
            age=Integer.parseInt(ageText);
            if(age<=0 || age>=120){
                JOptionPane.showMessageDialog(this,"Please enter a valid age");
            }
        }
        catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this,"Age must be a number");
            return;
        }
        
        String sql="INSERT INTO patients"+"(name,age,gender,phone,address)"+"VALUES(?,?,?,?,?)";
        
        try(Connection con=DBConnection.getConnection()){
            if(con==null){
                JOptionPane.showMessageDialog(this,"Database Connection Failed.");
                return;
            }
        
            try(PreparedStatement pst=con.prepareStatement(sql,java.sql.Statement.RETURN_GENERATED_KEYS)){
                pst.setString(1,name);
                pst.setInt(2, age);
                pst.setString(3, gender);
                pst.setString(4, phone);
                pst.setString(5, address);
                
                int rows=pst.executeUpdate();
                if(rows>0){
                    try(java.sql.ResultSet rs=pst.getGeneratedKeys()){
                        if(rs.next()){
                            int patientId=rs.getInt(1);
                            txtPatientID.setText(String.valueOf(patientId));
                        }
                    }
                    JOptionPane.showMessageDialog(this,"Patient details saved successfully");
                }
            }
        }catch(SQLException e){
            JOptionPane.showMessageDialog(this,"Error saving patient :"+ e.getMessage());
        }
                
    }//GEN-LAST:event_btnSaveActionPerformed

