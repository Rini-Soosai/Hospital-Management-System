    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        String sql="UPDATE patients SET name=?,age=?,gender=?,phone=?,address=? WHERE patient_id=?";
        
        try{
            Connection con=DBConnection.getConnection();
            if(con==null){
                JOptionPane.showMessageDialog(this,"Database creation failed.");
                return;
            }
            PreparedStatement pst=con.prepareStatement(sql);
            
            pst.setString(1, txtPatientName.getText().trim());
            pst.setInt(2,Integer.parseInt(txtAge.getText().trim()));
            
            String gender="";
            if(rdoMale.isSelected()){
                gender="Male";}
            else if(rdoFemale.isSelected()){
                gender="Female";}
            else if(rdoOther.isSelected()){
                gender="Other";}
            
            pst.setString(3, gender);
            pst.setString(4,txtPhoneNumber.getText().trim());
            pst.setString(5, txtAddress.getText().trim());
            pst.setInt(6,Integer.parseInt(txtPatientID.getText().trim()));
            
            int rows=pst.executeUpdate();
            
            if(rows>0){
               JOptionPane.showMessageDialog(this, "Patient details updated successfully.");
               this.dispose();
            }
            else{
                JOptionPane.showMessageDialog(this, "Patient record not found.");
            }
            pst.close();
            con.close();
            
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this,"Enter a valid Patient ID and Age.");
        }catch(SQLException e){
            JOptionPane.showMessageDialog(this, "Error updating patient"+e.getMessage());}
    }//GEN-LAST:event_btnUpdateActionPerformed

