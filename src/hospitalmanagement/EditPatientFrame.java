    private void loadPatientDetails(int patientID){
        String sql="SELECT *FROM patients WHERE patient_id=?";
        
        try(Connection con=DBConnection.getConnection();
                PreparedStatement pst=con.prepareStatement(sql)){
            pst.setInt(1, patientID);
            
            try(ResultSet rs=pst.executeQuery()){
                if(rs.next()){
                    txtPatientName.setText(rs.getString("name"));
                    txtAge.setText(String.valueOf(rs.getInt("age")));
                    
                    String gender=rs.getString("gender");
                    
                    if("Male".equalsIgnoreCase(gender)){
                        rdoMale.setSelected(true);
                    }else if("Female".equalsIgnoreCase(gender)){
                        rdoFemale.setSelected(true);
                    }else if("Other".equalsIgnoreCase(gender)){
                        rdoOther.setSelected(true);
                    }
                    txtPhoneNumber.setText(rs.getString("phone"));
                    txtAddress.setText(rs.getString("address"));
                }
            }
        }catch(SQLException e){
            JOptionPane.showMessageDialog(this, "Error loading patient details :"+e.getMessage());
        }
    }

